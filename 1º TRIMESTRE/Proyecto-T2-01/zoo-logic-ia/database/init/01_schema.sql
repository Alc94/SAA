-- Zoo-Logic IA - esquema inicial de PostgreSQL
-- Se ejecuta automaticamente al crear el volumen de la base de datos.

CREATE TABLE IF NOT EXISTS species (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    common_name         VARCHAR(100) NOT NULL UNIQUE,
    scientific_name     VARCHAR(120) NOT NULL,
    conservation_status VARCHAR(2)   NOT NULL DEFAULT 'LC'
        CHECK (conservation_status IN ('LC','NT','VU','EN','CR')),
    habitat             VARCHAR(200) NOT NULL,
    diet                VARCHAR(200) NOT NULL,
    educational_fact    VARCHAR(500) NOT NULL
);

CREATE TABLE IF NOT EXISTS animals (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(80)   NOT NULL,
    tag_code      VARCHAR(40)   NOT NULL UNIQUE,
    species_id    INTEGER       NOT NULL REFERENCES species(id) ON DELETE RESTRICT,
    sex           VARCHAR(12)   NOT NULL DEFAULT 'Desconocido'
        CHECK (sex IN ('Macho','Hembra','Desconocido')),
    birth_date    DATE,
    weight_kg     NUMERIC(8,2)  NOT NULL DEFAULT 0 CHECK (weight_kg >= 0),
    enclosure     VARCHAR(80)   NOT NULL,
    health_status VARCHAR(20)   NOT NULL DEFAULT 'Saludable'
        CHECK (health_status IN ('Saludable','En observación','Crítico')),
    notes         VARCHAR(1000),
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_animals_species_id    ON animals(species_id);
CREATE INDEX IF NOT EXISTS ix_animals_health_status ON animals(health_status);

CREATE TABLE IF NOT EXISTS vet_records (
    id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id            INTEGER      NOT NULL REFERENCES animals(id) ON DELETE CASCADE,
    record_date          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    record_type          VARCHAR(30)  NOT NULL,
    description          VARCHAR(1000) NOT NULL,
    temperature_c        NUMERIC(4,1),
    heart_rate_bpm       INTEGER CHECK (heart_rate_bpm IS NULL OR heart_rate_bpm > 0),
    source               VARCHAR(20)  NOT NULL DEFAULT 'Veterinario'
        CHECK (source IN ('Veterinario','IoT','Visión','IA')),
    anomaly_score        NUMERIC(3,2) CHECK (anomaly_score IS NULL OR (anomaly_score >= 0 AND anomaly_score <= 1)),
    veterinarian         VARCHAR(80)  NOT NULL,
    validated_by_expert  BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE INDEX IF NOT EXISTS ix_vet_records_animal_id   ON vet_records(animal_id);
CREATE INDEX IF NOT EXISTS ix_vet_records_record_date ON vet_records(record_date DESC);
